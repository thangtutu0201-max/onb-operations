export function parseCsvSchedules(csvText: string): WorkSchedule[] {
  const lines = csvText.split('\n').map(l => l.trim()).filter(Boolean);
  const schedules: WorkSchedule[] = [];
  let currentDates: string[] = []; // YYYY-MM-DD for 7 days

  let i = 0;
  while (i < lines.length) {
    const line = lines[i];

    if (line.includes('Thứ 2') && line.includes('Thứ 3')) {
      // Header 1: Days of week
      i++;
      if (i >= lines.length) break;
      const dateLine = lines[i];
      // Date row like: ,29/06,,30/06,,01/07,,02/07,,03/07,,04/07,,05/07,
      const parts = dateLine.split(',').map(s => s.trim());
      // Indices for 7 days: 1, 3, 5, 7, 9, 11, 13
      const dayIndices = [1, 3, 5, 7, 9, 11, 13];
      currentDates = dayIndices.map(idx => {
        const rawDate = parts[idx];
        if (!rawDate) return '';
        const [d, m] = rawDate.split('/');
        if (!d || !m) return '';
        const day = d.padStart(2, '0');
        const month = m.padStart(2, '0');
        const year = month === '01' ? '2027' : '2026';
        return `${year}-${month}-${day}`;
      });
      i++;
      continue;
    }

    // Check if this line starts with an ONB name
    const partsA = line.split(',').map(s => s.trim());
    const potentialName = partsA[0];

    if (potentialName && MEMBER_MAP[potentialName]) {
      const onbCode = MEMBER_MAP[potentialName];
      // Next line is sub-line
      let partsB: string[] = [];
      if (i + 1 < lines.length && lines[i + 1].startsWith(',')) {
        partsB = lines[i + 1].split(',').map(s => s.trim());
        i++; // skip sub-line
      }

      // Each day has 2 sub-columns:
      // Day 0: indices 1 (type), 2 (task) in partsA; indices 1 (sub1), 2 (sub2) in partsB
      // Day 1: indices 3, 4
      // Day 2: indices 5, 6
      // Day 3: indices 7, 8
      // Day 4: indices 9, 10
      // Day 5: indices 11, 12
      // Day 6: indices 13, 14
      for (let dayIdx = 0; dayIdx < 7; dayIdx++) {
        const dateStr = currentDates[dayIdx];
        if (!dateStr) continue;

        const colType = partsA[1 + dayIdx * 2] || '';
        const colTask = partsA[2 + dayIdx * 2] || '';
        const subType = partsB[1 + dayIdx * 2] || '';
        const subTask = partsB[2 + dayIdx * 2] || '';

        const isWeekend = dayIdx === 5 || dayIdx === 6;

        // If line A has an entry -> Sáng
        if (colType || colTask) {
          const wt = colType || (colTask.includes('Học') ? 'Đào tạo' : 'TVTK_TT');
          const product = subType || (colTask.includes('CRM') ? 'CRM' : colTask.includes('HRM') ? 'HRM' : undefined);

          schedules.push({
            id: `sch_csv_${schedules.length + 1}`,
            onbCode,
            collaborators: [],
            date: dateStr,
            sessionOfDay: 'Sáng',
            workTypeCode: wt,
            productCode: product,
            customerOrTask: colTask || colType,
            notes: subType ? `Nghiệp vụ: ${subType}` : undefined,
            status: 'Hoàn thành',
            trackCompensatoryLeave: isWeekend,
            isCompleted: true,
            monthYear: dateStr.slice(0, 7),
            createdAt: '2026-10-01',
            updatedAt: '2026-10-01',
            updatedBy: 'SYSTEM_EXCEL'
          });

          // If line B also has a distinct task, it is Chiều
          if (subTask && subTask !== colTask && !['CRM', 'HRM', 'KHO', 'MUA', 'SX', 'KẾ TOÁN'].includes(subTask.toUpperCase())) {
            schedules.push({
              id: `sch_csv_${schedules.length + 1}`,
              onbCode,
              collaborators: [],
              date: dateStr,
              sessionOfDay: 'Chiều',
              workTypeCode: subType || wt,
              customerOrTask: subTask,
              status: 'Hoàn thành',
              trackCompensatoryLeave: isWeekend,
              isCompleted: true,
              monthYear: dateStr.slice(0, 7),
              createdAt: '2026-10-01',
              updatedAt: '2026-10-01',
              updatedBy: 'SYSTEM_EXCEL'
            });
          }
        } else if (subType || subTask) {
          // Only sub-line had text -> Chiều
          schedules.push({
            id: `sch_csv_${schedules.length + 1}`,
            onbCode,
            collaborators: [],
            date: dateStr,
            sessionOfDay: 'Chiều',
            workTypeCode: subType || 'Hỗ trợ',
            customerOrTask: subTask || subType,
            status: 'Hoàn thành',
            trackCompensatoryLeave: isWeekend,
            isCompleted: true,
            monthYear: dateStr.slice(0, 7),
            createdAt: '2026-10-01',
            updatedAt: '2026-10-01',
            updatedBy: 'SYSTEM_EXCEL'
          });
        }
      }
    }

    i++;
  }

  return schedules;
}
